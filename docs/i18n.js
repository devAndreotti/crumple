  var STRINGS = { en: EN, pt: PT };

  function safeGet(k) { try { return localStorage.getItem(k); } catch (e) { return null; } }
  function safeSet(k, v) { try { localStorage.setItem(k, v); } catch (e) { /* storage blocked: keep the default */ } }

  // ?lang=pt or ?lang=en (a deep link) wins over the stored choice for this load; it is not stored by itself
  function fromUrl() {
    try {
      var m = /[?&]lang=(en|pt)(?:&|$)/.exec(location.search);
      return m ? m[1] : null;
    } catch (e) { return null; }
  }

  function setMeta(sel, value) {
    var node = document.querySelector(sel);
    if (node) node.setAttribute('content', value);
  }

  function detect() {
    var fromLink = fromUrl();
    if (fromLink) return fromLink;
    var stored = safeGet(STORE_KEY);
    if (stored === 'en' || stored === 'pt') return stored;
    var nav = (navigator.language || 'en').toLowerCase();
    return nav.indexOf('pt') === 0 ? 'pt' : 'en';
  }

  var lang = detect();

  window.SiteI18n = {
    lang: lang,
    t: function (key) {
      var d = STRINGS[lang] || EN;
      return d[key] != null ? d[key] : (EN[key] != null ? EN[key] : key);
    },
    // paper overrides for the active language (text, back, hiddenInk), or an empty object for English
    paper: function (id) {
      return (lang !== 'en' && PAPER_TEXTS[lang] && PAPER_TEXTS[lang][id]) || {};
    },
    sceneLabels: function () {
      if (lang === 'pt') {
        return { flip: '[ virar ]', tear: '[ rasgar canhoto ]', close: '[ fechar ]', hint: 'arraste para desamassar', open: 'Papel amassado: abrir', back: 'Verso:' };
      }
      return { flip: '[ flip ]', tear: '[ tear stub ]', close: '[ close ]', hint: 'drag to unfold', open: 'Crumpled paper: open', back: 'Back:' };
    },
    // applies the strings to every element with data-i18n (text), data-i18n-aria (aria-label) and the title
    apply: function (root) {
      var scope = root || document;
      var nodes = scope.querySelectorAll('[data-i18n]');
      for (var i = 0; i < nodes.length; i++) {
        var key = nodes[i].getAttribute('data-i18n');
        nodes[i].textContent = this.t(key);
      }
      var aria = scope.querySelectorAll('[data-i18n-aria]');
      for (var j = 0; j < aria.length; j++) {
        aria[j].setAttribute('aria-label', this.t(aria[j].getAttribute('data-i18n-aria')));
      }
      document.documentElement.lang = lang === 'pt' ? 'pt-BR' : 'en';
      document.title = this.t('meta.title');
      setMeta('meta[name="description"]', this.t('meta.description'));
      setMeta('meta[property="og:title"]', this.t('meta.title'));
      setMeta('meta[property="og:description"]', this.t('meta.description'));
      setMeta('meta[property="og:image:alt"]', this.t('meta.imageAlt'));
      setMeta('meta[property="og:locale"]', lang === 'pt' ? 'pt_BR' : 'en_US');
      setMeta('meta[property="og:locale:alternate"]', lang === 'pt' ? 'en_US' : 'pt_BR');
    },
    // stores the choice and reloads, so every paper is created in the new language. A ?lang= link is
    // dropped from the address first, otherwise the reload would bring the old language back
    set: function (next) {
      if (next !== 'en' && next !== 'pt') return;
      safeSet(STORE_KEY, next);
      if (next === lang) return;
      try {
        var u = new URL(location.href);
        if (u.searchParams.has('lang')) {
          u.searchParams.delete('lang');
          history.replaceState(null, '', u.pathname + u.search + u.hash);
        }
      } catch (e) { /* no URL API: the reload keeps the link's language */ }
      location.reload();
    }
  };
